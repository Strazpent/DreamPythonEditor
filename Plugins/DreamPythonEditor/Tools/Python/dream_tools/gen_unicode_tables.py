"""Generates DreamCore's Python character tables from the engine's own interpreter (TDD 4.3.1, T-LEX-004).

Run with the engine's python.exe in isolated mode, from any directory:

    "<UE>/Engine/Binaries/ThirdParty/Python3/Win64/python.exe" -I -B Tools/Python/dream_tools/gen_unicode_tables.py

It writes, under Source/DreamCore/Private/:
  XidTables.inc    identifier start / continue ranges, so dream::utf::IsIdentifier equals str.isidentifier()
  PyBuiltins.inc   the sorted names of dir(builtins), for dream::PyLexer::IsBuiltin
  Cp1252Table.inc  Python's cp1252 decoding of 0x80..0x9F (0 = undefined), for dream::codec

The files are data only and are checked in; regenerate them when the engine's Python version changes.
"""

import builtins
import os
import sys
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
PRIVATE = os.path.normpath(os.path.join(HERE, "..", "..", "..", "Source", "DreamCore", "Private"))

HEADER = (
    "// SPDX-License-Identifier: Apache-2.0\n"
    "// Generated by Tools/Python/dream_tools/gen_unicode_tables.py on Python {ver} (Unicode {uni}). Do not edit.\n"
)


def ranges(predicate):
    out = []
    start = None
    for cp in range(0x110000):
        ok = predicate(cp)
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def is_start(cp):
    if 0xD800 <= cp <= 0xDFFF:
        return False
    return chr(cp).isidentifier()


def is_continue(cp):
    if 0xD800 <= cp <= 0xDFFF:
        return False
    return ("a" + chr(cp)).isidentifier()


def write(name, body):
    path = os.path.join(PRIVATE, name)
    text = HEADER.format(ver=sys.version.split()[0], uni=unicodedata.unidata_version) + body
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", path)


def range_array(var, items):
    lines = ["inline constexpr XidRange %s[] = {" % var]
    row = []
    for a, b in items:
        row.append("{0x%X, 0x%X}," % (a, b))
        if len(row) == 6:
            lines.append("\t" + " ".join(row))
            row = []
    if row:
        lines.append("\t" + " ".join(row))
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    start = ranges(is_start)
    cont = ranges(is_continue)
    body = "// Included once, by Utf.cpp, inside namespace dream::utf_tables.\n"
    body += "struct XidRange\n{\n\tchar32_t First;\n\tchar32_t Last;\n};\n\n"
    body += "// Code points c with chr(c).isidentifier() (XID_Start plus '_').\n"
    body += range_array("XidStartRanges", start) + "\n"
    body += "// Code points c with ('a' + chr(c)).isidentifier() (XID_Continue).\n"
    body += range_array("XidContinueRanges", cont)
    write("XidTables.inc", body)

    names = sorted(dir(builtins))
    body = "// Included once, by PyLexer.cpp, inside namespace dream::lexer_tables. Sorted (ordinal) for binary search.\n"
    body += "inline constexpr const char16_t* BuiltinNames[] = {\n"
    for n in names:
        body += '\tu"%s",\n' % n
    body += "};\n"
    write("PyBuiltins.inc", body)

    table = []
    for b in range(0x80, 0xA0):
        try:
            table.append(ord(bytes([b]).decode("cp1252")))
        except UnicodeDecodeError:
            table.append(0)
    body = "// Included once, by TextCodec.cpp, inside namespace dream::codec_tables. Bytes 0x80..0x9F; 0 = undefined.\n"
    body += "inline constexpr char16_t Cp1252High[32] = {\n"
    for i in range(0, 32, 8):
        body += "\t" + " ".join("0x%04X," % v for v in table[i:i + 8]) + "\n"
    body += "};\n"
    write("Cp1252Table.inc", body)


if __name__ == "__main__":
    main()
