"""Writes Source/DreamEditorTests/Private/Fixtures/DreamTestGetterFixture.h: the TDD 14.2 fixture UObject with 1,000
BlueprintGetter-backed properties whose getters count their calls (T-RES-017, T-INSP-002: "never calls a getter" is an
assertion). UHT does not expand macros, so the 2,000 declarations are generated text; run this again after a change.

Usage: python.exe -I -B gen_getter_fixture.py [--count 1000]
"""

import argparse
import os

HERE = os.path.dirname(os.path.abspath(__file__))
TARGET = os.path.join(HERE, "..", "..", "Source", "DreamEditorTests", "Private", "Fixtures", "DreamTestGetterFixture.h")

HEAD = """// SPDX-License-Identifier: Apache-2.0
// GENERATED by Tests/ci/gen_getter_fixture.py (%(count)d properties): do not edit by hand.
// The getter-counting fixture UObject of TDD 14.2: %(count)d int32 properties, each read through a BlueprintGetter that
// counts its call, so a test asserts that Python attribute access, completion or an inspector made no getter call
// (C9: attribute reads call BlueprintGetters; get_editor_property does not). Repository only (DreamEditorTests).
// From Python: unreal.DreamTestGetterFixture.reset_getter_calls(), then unreal.DreamTestGetterFixture.get_getter_calls().
#pragma once

#include "CoreMinimal.h"
#include "UObject/Object.h"
#include "DreamTestGetterFixture.generated.h"

UCLASS(BlueprintType, Transient, meta = (DisplayName = "Dream Python Editor Test Getter Fixture"))
class UDreamTestGetterFixture : public UObject
{
	GENERATED_BODY()

public:
	/** Getter calls of every instance since the last reset. */
	UFUNCTION(BlueprintCallable, Category = "Dream|Tests")
	static int64 GetGetterCalls();

	UFUNCTION(BlueprintCallable, Category = "Dream|Tests")
	static void ResetGetterCalls();

	/** The number of getter-backed properties (%(count)d). */
	UFUNCTION(BlueprintCallable, Category = "Dream|Tests")
	static int32 GetPropertyCount() { return %(count)d; }

"""

PROPERTY = """	UPROPERTY(BlueprintGetter = GetValue%(n)04d, Category = "Dream|Tests")
	int32 Value%(n)04d = %(n)d;
	UFUNCTION(BlueprintGetter)
	int32 GetValue%(n)04d() const { CountGetterCall(); return Value%(n)04d; }
"""

TAIL = """
private:
	static void CountGetterCall();
};
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--count", type=int, default=1000)
    args = parser.parse_args()
    parts = [HEAD % {"count": args.count}]
    for n in range(args.count):
        parts.append(PROPERTY % {"n": n})
    parts.append(TAIL)
    with open(os.path.abspath(TARGET), "w", encoding="utf-8", newline="\n") as handle:
        handle.write("".join(parts))
    print("wrote %s" % os.path.abspath(TARGET))


if __name__ == "__main__":
    main()
