# Generates Source/DreamCore/Private/SearchTables.inc for dream::SearchEngine (TDD §4.4) from the engine's CPython
# 3.11.8, so the regex classes and IGNORECASE folding equal Python's `re` on str patterns:
#   \w = str.isalnum() or '_'   \d = str.isdecimal()   \s = str.isspace()   (_sre.c SRE_UNI_IS_*)
#   fold: two characters match case-insensitively when their lowercase forms (_sre.unicode_tolower) are equal or
#   linked by re._casefix._EXTRA_CASES (re/_compiler.py); Fold maps a code point to the smallest such form.
#   Upper/Lower: single-character str.upper()/str.lower() (preserve-case replace).
#   SreLower: _sre.unicode_tolower, what an IGNORECASE backreference compares (sre GROUPREF_UNI_IGNORE).
# Run: "<engine>/Engine/Binaries/ThirdParty/Python3/Win64/python.exe" -I gen_search_tables.py <output .inc>
import sys
import unicodedata

import _sre
from re._casefix import _EXTRA_CASES


def ranges(pred):
    out = []
    start = None
    for cp in range(0x110000 + 1):
        ok = cp <= 0x10FFFF and not (0xD800 <= cp <= 0xDFFF) and pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def emit_ranges(f, name, rs):
    f.write("\tinline constexpr uint32_t %s[] = {\n" % name)
    for i in range(0, len(rs), 6):
        f.write("\t\t" + " ".join("0x%X, 0x%X," % r for r in rs[i:i + 6]) + "\n")
    f.write("\t};\n")


def emit_pairs(f, name, pairs):
    f.write("\tinline constexpr uint32_t %s[] = {\n" % name)
    for i in range(0, len(pairs), 6):
        f.write("\t\t" + " ".join("0x%X, 0x%X," % p for p in pairs[i:i + 6]) + "\n")
    f.write("\t};\n")


def main():
    out_path = sys.argv[1]
    word = ranges(lambda c: c.isalnum() or c == "_")
    digit = ranges(lambda c: c.isdecimal())
    space = ranges(lambda c: c.isspace())
    fold = []
    groups = {}
    upper = []
    lower = []
    sre_lower = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        lo = _sre.unicode_tolower(cp)
        if lo != cp:
            sre_lower.append((cp, lo))
        canon = min((lo,) + tuple(_EXTRA_CASES.get(lo, ())))
        if canon != cp:
            fold.append((cp, canon))
        groups.setdefault(canon, []).append(cp)
        c = chr(cp)
        u = c.upper()
        if len(u) == 1 and u != c:
            upper.append((cp, ord(u)))
        l = c.lower()
        if len(l) == 1 and l != c:
            lower.append((cp, ord(l)))
    members = []
    for canon in sorted(groups):
        if len(groups[canon]) > 1:
            for m in sorted(groups[canon]):
                members.append((canon, m))
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("// SPDX-License-Identifier: Apache-2.0\n")
        f.write("// Generated by Tests/DreamCore/gen_search_tables.py from CPython %s (Unicode %s); do not edit.\n"
                % (sys.version.split()[0], unicodedata.unidata_version))
        f.write("// Pairs are (first, last) ranges or (from, to) maps, sorted by the first value.\n")
        emit_ranges(f, "WordRanges", word)
        emit_ranges(f, "DigitRanges", digit)
        emit_ranges(f, "SpaceRanges", space)
        emit_pairs(f, "FoldMap", fold)
        emit_pairs(f, "FoldMembers", members)
        emit_pairs(f, "UpperMap", upper)
        emit_pairs(f, "LowerMap", lower)
        emit_pairs(f, "SreLowerMap", sre_lower)
    print("word", len(word), "digit", len(digit), "space", len(space), "fold", len(fold), "members", len(members),
          "upper", len(upper), "lower", len(lower), "sre_lower", len(sre_lower))


main()
